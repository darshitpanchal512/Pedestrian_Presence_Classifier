from PIL import Image # PIT= Python imaging library

def predict_image(image_path, threshold=0.5):
    img = Image.open(image_path).convert("RGB")
    x = test_transform(img).unsqueeze(0).to(device)

    with torch.no_grad():
        prob = model(x).item()   # sigmoid output between 0 and 1

    if prob >= threshold:
        label = "Pedestrian"
        confidence = prob
    else:
        label = "No Pedestrian"
        confidence = 1 - prob

    return label, confidence * 100.0  # percent

